/**
 * PROMPT 3 Implementation: Memory Architecture
 *
 * Four-layer memory system:
 * 1. Immutable Identity Memory (rarely changes)
 * 2. Long-term Vision Memory (evolves slowly)
 * 3. Short-term Conversational Memory (session-based)
 * 4. Reflection Summaries (post-conversation insights)
 */

import { FutureSelfModel } from './FutureSelf';

/**
 * Layer 1: Immutable Identity Memory
 * Core identity, values, and personality that rarely change
 * Update frequency: Only when user explicitly recalibrates their Future Self
 */
export interface ImmutableIdentityMemory {
  futureSelf: FutureSelfModel;
  lastCalibrationDate: string;
  calibrationCount: number;
}

/**
 * Layer 2: Long-term Vision Memory
 * Goals, patterns, recurring themes across conversations
 * Update frequency: After each conversation, accumulated over time
 */
export interface VisionMemoryEntry {
  id: string;
  type: 'goal' | 'pattern' | 'struggle' | 'growth' | 'regression';
  content: string;
  firstMentioned: string;
  lastMentioned: string;
  frequency: number; // How many times this has come up
  resolved: boolean;
  tags: string[];
}

export interface LongTermVisionMemory {
  entries: VisionMemoryEntry[];
  recurringPatterns: string[]; // User keeps struggling with these
  emergingGrowth: string[]; // New positive patterns
  goalsInProgress: string[];
  trackedGoals: TrackedGoal[];
  lastUpdated: string;
}

/**
 * Layer 3: Short-term Conversational Memory
 * Current session context
 * Update frequency: Real-time during conversation
 */
export interface Message {
  id: string;
  role: 'user' | 'assistant';
  content: string;
  timestamp: string;
}

export interface ConversationSession {
  id: string;
  startedAt: string;
  endedAt?: string;
  messages: Message[];
  context: {
    userMood?: 'energized' | 'calm' | 'anxious' | 'sad' | 'frustrated' | 'stressed' | 'motivated' | 'avoidant' | 'reflective' | 'defensive';
    topicArea?: string; // What the conversation is about
    urgency?: 'low' | 'medium' | 'high';
  };
  wasReflectionGenerated: boolean;
}

/**
 * Layer 4: Reflection Summaries
 * Post-conversation insights generated by Future Self
 * Update frequency: After each conversation ends
 */
export interface ReflectionSummary {
  id: string;
  conversationId: string;
  createdAt: string;

  whatHappened: string; // Neutral summary of the conversation
  keyInsights: string[]; // What became clear
  misalignmentsDetected: string[]; // Where current behavior contradicts future identity
  recommendedActions: string[]; // Concrete next steps
  progressIndicators: string[]; // Signs of growth or regression

  // Conflict detection (PROMPT 3 requirement)
  conflictsWithIdentity: {
    behavior: string;
    contradicts: string; // Which part of future self identity
    severity: 'low' | 'medium' | 'high';
  }[];

  emotionalTone: 'supportive' | 'challenging' | 'warning' | 'celebratory';
}

/**
 * Streak tracking
 */
export interface StreakData {
  currentStreak: number;
  longestStreak: number;
  lastActiveDate: string; // YYYY-MM-DD
  totalDays: number;
}

/**
 * Goal tracking with accountability
 */
export interface TrackedGoal {
  id: string;
  content: string;
  source: 'reflection' | 'manual' | 'conversation';
  createdAt: string;
  status: 'active' | 'completed' | 'abandoned';
  completedAt?: string;
}

/**
 * Offline message queue
 */
export interface QueuedMessage {
  id: string;
  userMessage: string;
  timestamp: string;
  retryCount: number;
}

/**
 * Weekly digest
 */
export interface WeeklyDigest {
  id: string;
  weekOf: string;
  createdAt: string;
  summary: string;
  conversationCount: number;
  topPatterns: string[];
  progressMade: string[];
  focusArea: string;
}

/**
 * Daily challenge
 */
export interface DailyChallenge {
  id: string;
  date: string; // YYYY-MM-DD
  challenge: string;
  status: 'pending' | 'completed' | 'skipped';
}

/**
 * Complete Memory System State
 */
export interface MemoryArchitecture {
  immutable: ImmutableIdentityMemory;
  longTerm: LongTermVisionMemory;
  currentSession: ConversationSession | null;
  reflections: ReflectionSummary[];
}

/**
 * Drift Prevention (PROMPT 3 requirement)
 *
 * Rules:
 * 1. Immutable memory can only change via explicit user recalibration
 * 2. Long-term memory entries require 3+ mentions before being considered "recurring"
 * 3. Reflections must reference specific messages from the conversation
 * 4. Conflicts are escalated to the user if severity is 'high' and recurring
 * 5. Future Self cannot promise outcomes or make predictions - only speak from consequence
 */
export interface DriftPreventionLog {
  timestamp: string;
  detectedDrift: {
    type: 'hallucination' | 'inconsistency' | 'fantasy-reinforcement';
    description: string;
    correctionTaken: string;
  }[];
}
